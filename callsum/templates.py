NAMES = {key: name for key, name, _when, _body in TEMPLATES}
CHOICES = [(AUTO, "Определять автоматически")] + [(k, n) for k, n, _w, _b in TEMPLATES] + [(CUSTOM, "Свой шаблон")]


def label(key: str) -> str:
    return dict(CHOICES).get(key, "")


def _common(when: datetime) -> str:
    date = f"{WEEKDAYS[when.weekday()]}, {when:%d.%m.%Y}"
    return f"""\
Правила оформления:
- Первой строкой — заголовок первого уровня с коротким названием встречи (3–7 слов), например «# Планирование релиза 2.4».
- В разделе «Задачи» — чек-лист «- [ ] Кто — что сделать — срок». Созвон был в {date}: если срок \
можно вычислить («к пятнице», «завтра»), пиши дату ДД.ММ.ГГГГ, иначе — как прозвучал. \
Если исполнитель или срок не прозвучали, пиши «не указан».
- Последний раздел — «## Хронология»: 3–12 пунктов «- [ЧЧ:ММ:СС] Тема» по порядку — с какого \
момента записи начинается каждая тема разговора.
- Пиши только то, что действительно прозвучало, ничего не додумывай. Если раздел пустой, напиши «—»."""


def instructions(choice: str, custom_prompt: str, when: datetime) -> str:
    """Задание для модели: структура саммари под выбранный шаблон."""
    head = "Сделай саммари этого созвона на русском языке в формате Markdown."
    if choice == CUSTOM:
        return f"{custom_prompt.strip()}\n\n{_common(when)}"
    if choice in NAMES:
        body = next(b for k, _n, _w, b in TEMPLATES if k == choice)
        return f"{head}\n\nРазделы после заголовка:\n\n{body}\n\n{_common(when)}"
    types = "\n\n".join(f"### {key} — {name}: {when_}\n{body}" for key, name, when_, body in TEMPLATES)
    return f"""{head}

Сначала определи тип встречи и выбери для него структуру из списка ниже. Самой первой строкой ответа \
напиши служебную пометку с ключом типа, например <!-- template: standup -->, а дальше — саммари \
по структуре этого типа.

{types}

{_common(when)}"""


_MARKER = re.compile(r"\A\s*<!--\s*template:\s*([a-z_]+)\s*-->\s*\n?")


def split_marker(text: str) -> tuple[str, str]:
    """Убирает служебную пометку о шаблоне: (текст без неё, ключ или "")."""
    m = _MARKER.match(text)
    if not m:
        return text, ""
    key = m.group(1)
    return text[m.end():], key if key in NAMES else ""


def hide_partial_marker(text: str) -> str:
    """Пока ответ пишется, недописанная пометка не должна мелькать в окне."""
    stripped, _ = split_marker(text)
    if stripped is not text:
        return stripped
    return "" if text.lstrip().startswith("<!--") and "-->" not in text else text
